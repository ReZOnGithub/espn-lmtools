"""Netscape cookie-jar helpers shared by the CLI and dashboard."""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path


def parse_netscape(path: Path) -> dict[str, str]:
    jar: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("#HttpOnly_"):
            line = line[len("#HttpOnly_") :]
        elif line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) >= 7:
            jar[parts[5]] = parts[6]
    return jar


def load_cookies(path: Path) -> dict[str, str]:
    jar = parse_netscape(path)
    if "SWID" not in jar or "espn_s2" not in jar:
        raise ValueError(f"{path.name}: needs both espn_s2 and SWID")
    return {"SWID": jar["SWID"], "espn_s2": jar["espn_s2"]}


def write_netscape(jar: Iterable[dict], path: Path, note: str = "espn_lmtools") -> None:
    lines = ["# Netscape HTTP Cookie File", f"# generated by {note}", ""]
    for cookie in jar:
        domain = cookie.get("domain") or ""
        prefix = "#HttpOnly_" if cookie.get("httpOnly") else ""
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        secure = "TRUE" if cookie.get("secure") else "FALSE"
        expires = int(cookie["expires"]) if cookie.get("expires") and cookie["expires"] > 0 else 0
        cookie_path = cookie.get("path") or "/"
        lines.append(
            f"{prefix}{domain}\t{include_sub}\t{cookie_path}\t{secure}\t{expires}"
            f"\t{cookie['name']}\t{cookie['value']}"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
